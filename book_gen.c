/*
 * book_gen.c
 * Host tool to generate an opening book for the Game Boy Chess Engine.
 * * Compiles with the engine core to ensure identical hashing:
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <ctype.h>
#include "chess.h"
#include "eval.h"
#include "engine.h"

// --- Output Structure (Must match what the engine expects) ---
typedef struct {
    uint16_t hash;
    uint8_t from;
    uint8_t to;
} BookEntry;

#define MAX_ENTRIES 4096
BookEntry entries[MAX_ENTRIES];
int entry_count = 0;

// Track the deepest move found in the entire book
int global_max_ply = 0;

// Comparison function for qsort (Sort by Hash)
int compare_entries(const void *a, const void *b) {
    // Note: We cast to uint16_t before subtracting to handle wrapping correctly? 
    // Actually standard integer subtraction is fine for sorting.
    return ((BookEntry *) a)->hash - ((BookEntry *) b)->hash;
}

// --- Helper: Parse coordinate string "e2" -> index ---
int parse_square(const char *sq_str) {
    if (strlen(sq_str) < 2)
        return -1;
    int col = sq_str[0] - 'a';
    int row = sq_str[1] - '1';
    if (col < 0 || col > 7 || row < 0 || row > 7)
        return -1;
    return (row * 16) + col;
}

// --- Helper: Find legal move that matches "e2e4" ---
// We need this to get the correct 'captured' and 'special' flags
// so the engine's make_move updates the hash correctly.
int find_and_parse_move(const char *move_str, Move *result) {
    // Parse Input "e2e4"
    int from = parse_square(move_str);
    int to = parse_square(move_str + 2);

    if (from == -1 || to == -1)
        return 0;

    // Generate ALL legal moves for current position
    Move moves[MAX_MOVES];
    uint8_t count = generate_moves(moves);

    // Find the matching move
    for (uint8_t i = 0; i < count; i++) {
        if (moves[i].from == from && moves[i].to == to) {
            *result = moves[i];

            // Special handling for Promotion in input string (e.g., "a7a8q")
            // The engine generates promotions with special=
            // If the user string implies promotion, we must match it.
            // For simplicity, we assume the first match is correct (usually is).
            return 1;
        }
    }
    return 0;
}

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "Usage: ./book_gen book.txt > book_data.c\n");
        return 1;
    }

    FILE *f = fopen(argv[1], "r");
    if (!f) {
        perror("Error opening book file");
        return 1;
    }

    char line[256];

    // Header for output file
    printf("/* Generated by book_gen.c */\n");
    printf("#include <stdint.h>\n");
    printf("#include \"chess.h\"\n");
    printf("#include \"book.h\"\n\n");
    printf("const BookEntry opening_book[] = {\n");

    while (fgets(line, sizeof(line), f)) {
        // Skip comments and empty lines
        char *p = line;
        while (*p && isspace((unsigned char) *p))
            p++;                // Skip leading whitespace
        if (*p == '\0' || *p == '#')
            continue;           // Skip empty or comment

        // Reset board for every new line of moves
        init_board();

        // Track ply for this specific line
        int current_ply = 0;

        // Tokenize line (split by space)
        char *token = strtok(line, " \t\r\n");
        while (token) {
            // Save current position hash (Move FROM this position)
            uint16_t current_hash = posHash;

            // Parse and validate the move
            Move m;
            if (!find_and_parse_move(token, &m)) {
                fprintf(stderr, "WARNING: Illegal or unparseable move '%s' for Hash %04X. Skipping line.\n", token, current_hash);
                break;
            }
            // Store entry
            if (entry_count < MAX_ENTRIES) {
                entries[entry_count].hash = current_hash;
                entries[entry_count].from = m.from;
                entries[entry_count].to = m.to;
                entry_count++;
            } else {
                fprintf(stderr, "ERROR: Book too large!\n");
                exit(1);
            }

            // Make move on internal board to advance state
            make_move(&m);

            //Increment and check max ply
            current_ply++;
            if (current_ply > global_max_ply) {
                global_max_ply = current_ply;
            }
            // Get next move in the line
            token = strtok(NULL, " \t\r\n");
        }
    }

    fclose(f);

    // Sort entries by Hash (Required for Binary Search on Game Boy)
    qsort(entries, (size_t) entry_count, sizeof(BookEntry), compare_entries);

    // Remove Duplicates
    // We filter in-place.
    if (entry_count > 0) {
        int unique_idx = 0;
        for (int i = 1; i < entry_count; i++) {
            // Check if this entry is DIFFERENT from the last unique one
            if (entries[i].hash != entries[unique_idx].hash || entries[i].from != entries[unique_idx].from || entries[i].to != entries[unique_idx].to) {

                unique_idx++;
                entries[unique_idx] = entries[i];
            }
            // If it IS the same, we just skip it (don't increment unique_idx)
        }
        // Update the total count
        entry_count = unique_idx + 1;
    }
    // Print Sorted Entries
    for (int i = 0; i < entry_count; i++) {
        // Simple optimization: If multiple lines have the same move for the same position,
        // we could deduplicate here. For now, we output all.
        // (Binary search finds *an* entry, randomizer can pick between duplicates if implemented)
        printf("    { 0x%04X, 0x%02X, 0x%02X },\n", entries[i].hash, entries[i].from, entries[i].to);
    }

    printf("};\n\n");
    printf("const uint16_t book_len = %d;\n", entry_count);
    printf("const uint8_t book_max_ply = %d;\n", global_max_ply);

    return 0;
}
